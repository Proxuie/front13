/*
 * Баллы рейтинга за призовые места.
 * Ключи совпадают с уровнем соревнования. Для всероссийских соревнований
 * и ЕКП используем ближайшие значения из кейса.
 */

const POINTS = {
  'Чемпионат России': { 1: 100, 2: 80, 3: 60 },
  'Первенство России': { 1: 80, 2: 60, 3: 40 },
  'Всероссийские': { 1: 80, 2: 60, 3: 40 },
  'Межрегиональные': { 1: 60, 2: 45, 3: 30 },
  'ЕКП': { 1: 60, 2: 45, 3: 30 },
  'Региональные': { 1: 40, 2: 30, 3: 20 },
};

function pointsFor(level, place) {
  const table = POINTS[level];
  if (!table) return 0;
  return table[place] || 0;
}

/* Коэффициент стабильности: 1.2, если призовых мест два и больше. */
function stabilityCoefficient(prizes) {
  return prizes >= 2 ? 1.2 : 1;
}

module.exports = { POINTS, pointsFor, stabilityCoefficient };
